param([switch]$Check)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName PresentationCore
$root = Split-Path $PSScriptRoot -Parent
$source = Get-Content "$root/../windows/Vex.App/Model/AppIconCatalog.generated.cs" -Raw
$zig = Get-Content "$root/src/terminal/app_icon.zig" -Raw
$enum = [regex]::Match($zig, 'pub const GlyphId = enum\(u8\) \{([\s\S]*?)\n\};').Groups[1].Value
$names = @([regex]::Matches($enum, '(?m)^    (\w+)(?: = 0)?,') | ForEach-Object { $_.Groups[1].Value })
$glyphs = @{}
foreach ($match in [regex]::Matches($source, 'new\("([^"]+)", "#[^"]+", "([^"]+)", ([^,]+), ([^,]+), ([^,]+), ([^)]+)\)')) {
    $glyphs[$match.Groups[1].Value] = @{ Path = $match.Groups[2].Value; X = $match.Groups[3].Value; Y = $match.Groups[4].Value; W = $match.Groups[5].Value; H = $match.Groups[6].Value }
}
foreach ($file in Get-ChildItem "$root/assets/icons/*.svg") {
    [xml]$svg = Get-Content $file.FullName -Raw
    $glyphs[$file.BaseName] = @{ Path = $svg.svg.path.d; X = '0'; Y = '0'; W = '24'; H = '24' }
}
# Explicit monograms for tools without a bundled brand path; never borrow an unrelated logo.
$badges = @{ lazygit = 'lg'; btop = 'bt'; ssh = 'S'; aider = 'ai'; emacs = 'em'; nano = 'na'; micro = 'mc'; yazi = 'ya'; zellij = 'ze' }
$culture = [Globalization.CultureInfo]::InvariantCulture
function Number([double]$value) { return $value.ToString('0.0####', $culture) + 'f' }
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('// Generated by tools/Generate-AppIconGeometry.ps1; do not edit.')
$lines.Add('// Brand paths: curated Simple Icons / CLI marks from AppIconCatalog.generated.cs (CC0/MIT).')
$lines.Add('#pragma once')
$lines.Add('#include <stdint.h>')
$lines.Add('enum class AppIconGlyph : uint8_t {')
for ($id = 0; $id -lt $names.Count; $id++) { $lines.Add("    $($names[$id]) = $id,") }
$lines.Add('};')
$lines.Add('struct AppIconFigure { uint32_t offset, count; bool closed; };')
$lines.Add('struct AppIconGeometry { const D2D1_POINT_2F* points; const AppIconFigure* figures; uint32_t figureCount; D2D1_FILL_MODE fill; const char* badge; };')
$entries = [Collections.Generic.List[string]]::new()
foreach ($name in $names) {
    if ($name -eq 'none') { $entries.Add('    { nullptr, nullptr, 0, D2D1_FILL_MODE_WINDING, "" },'); continue }
    if (!$glyphs.ContainsKey($name)) {
        if (!$badges.ContainsKey($name)) { throw "Vex icon geometry: no path or explicit badge for $name" }
        $entries.Add('    { nullptr, nullptr, 0, D2D1_FILL_MODE_WINDING, "' + $badges[$name] + '" },')
        continue
    }
    $match = $glyphs[$name]
    $viewX = [double]::Parse($match.X, $culture)
    $viewY = [double]::Parse($match.Y, $culture)
    $viewW = [double]::Parse($match.W, $culture)
    $viewH = [double]::Parse($match.H, $culture)
    $geometry = [Windows.Media.Geometry]::Parse($match.Path)
    $flat = $geometry.GetFlattenedPathGeometry(0.01, [Windows.Media.ToleranceType]::Absolute)
    $points = [Collections.Generic.List[string]]::new()
    $figures = [Collections.Generic.List[string]]::new()
    $scale = 24.0 / [Math]::Max($viewW, $viewH)
    foreach ($figure in $flat.Figures) {
        $offset = $points.Count
        $figurePoints = [Collections.Generic.List[Windows.Point]]::new()
        $figurePoints.Add($figure.StartPoint)
        foreach ($segment in $figure.Segments) {
            if ($segment -is [Windows.Media.PolyLineSegment]) { foreach ($point in $segment.Points) { $figurePoints.Add($point) } }
            elseif ($segment -is [Windows.Media.LineSegment]) { $figurePoints.Add($segment.Point) }
            else { throw "Vex icon geometry: unexpected flattened segment for $name" }
        }
        foreach ($point in $figurePoints) {
            $x = ($point.X - $viewX - $viewW / 2) * $scale + 12
            $y = ($point.Y - $viewY - $viewH / 2) * $scale + 12
            $points.Add('    { ' + (Number $x) + ', ' + (Number $y) + ' },')
        }
        $closed = if ($figure.IsClosed) { 'true' } else { 'false' }
        $figures.Add("    { $offset, $($figurePoints.Count), $closed },")
    }
    if (!$figures.Count) { throw "Vex icon geometry: empty path for $name" }
    $lines.Add("static constexpr D2D1_POINT_2F iconPoints_$name[] = {")
    $lines.AddRange($points)
    $lines.Add('};')
    $lines.Add("static constexpr AppIconFigure iconFigures_$name[] = {")
    $lines.AddRange($figures)
    $lines.Add('};')
    $fill = if ($flat.FillRule -eq [Windows.Media.FillRule]::Nonzero) { 'D2D1_FILL_MODE_WINDING' } else { 'D2D1_FILL_MODE_ALTERNATE' }
    $entries.Add("    { iconPoints_$name, iconFigures_$name, $($figures.Count), $fill, `"`" },")
}
$lines.Add('static constexpr AppIconGeometry appIconGeometries[] = {')
$lines.AddRange($entries)
$lines.Add('};')
$lines.Add('static_assert(sizeof(appIconGeometries) / sizeof(appIconGeometries[0]) == ' + $names.Count + ');')
$content = ($lines -join "`n") + "`n"
$path = "$root/src/windows/app_icon_geometry.generated.h"
if ($Check) {
    if (!(Test-Path $path) -or [IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $content) {
        throw 'Vex icon geometry: generated catalog is stale; run tools/Generate-AppIconGeometry.ps1'
    }
    Write-Output "PASS: $($names.Count - 1) icon IDs match Zig; $($glyphs.Count) source brand paths and explicit fallback badges."
} else {
    [IO.File]::WriteAllText($path, $content, [Text.UTF8Encoding]::new($false))
}
