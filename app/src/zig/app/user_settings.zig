    try temp.dir.writeFile(.{ .sub_path = "appearance.lua", .data = "\x1bLua" });
    try std.testing.expectError(error.InvalidLuaSettings, loadUserSettings(std.testing.allocator, path));
    const oversized = try std.testing.allocator.alloc(u8, max_config_bytes + 1);
    defer std.testing.allocator.free(oversized);
    @memset(oversized, ' ');
    try temp.dir.writeFile(.{ .sub_path = "appearance.lua", .data = oversized });
