    const allocator = std.testing.allocator;
    const light = try UserSettings.decode(allocator, "vex.config.appearance = 'light'");
    try std.testing.expectEqual(themes.default_light_index, light.theme_index);
    const encoded = try light.encodeAlloc(allocator);
    defer allocator.free(encoded);
