    try temp.dir.writeFile(.{ .sub_path = "init.lua", .data = oversized });
    try std.testing.expectError(error.FileTooBig, loadUserSettings(std.testing.allocator, path));
    for ([_][]const u8{ "require('../outside')", "require('C:/outside')", "require('missing')" }) |source| {
        try temp.dir.writeFile(.{ .sub_path = "init.lua", .data = source });
        try std.testing.expectError(error.InvalidLuaSettings, loadUserSettings(std.testing.allocator, path));
    }
    try std.testing.expectEqual(@as(u8, 18), (try UserSettings.decode(std.testing.allocator, "\xef\xbb\xbfvex.config.font_size = 18")).font_size);
}

test "custom Lua paths save preferences in place" {
    var temp = std.testing.tmpDir(.{});
    defer temp.cleanup();
    const root = try temp.dir.realpathAlloc(std.testing.allocator, ".");
    defer std.testing.allocator.free(root);
    const primary = try std.fs.path.join(std.testing.allocator, &.{ root, "gui.lua" });
    defer std.testing.allocator.free(primary);
    const alternate = try std.fs.path.join(std.testing.allocator, &.{ root, "alternate.lua" });
    defer std.testing.allocator.free(alternate);
    try temp.dir.writeFile(.{ .sub_path = "gui.lua", .data = "-- my user configuration" });
    try saveUserSettings(std.testing.allocator, primary, .{ .font_size = 23 });
    try std.testing.expectEqual(@as(u8, 23), (try loadUserSettings(std.testing.allocator, primary)).font_size);
    try std.testing.expectEqualDeep(UserSettings{}, try loadUserSettings(std.testing.allocator, alternate));
    const unchanged = try temp.dir.readFileAlloc(std.testing.allocator, "gui.lua", max_config_bytes);
    defer std.testing.allocator.free(unchanged);
    try std.testing.expectEqual(@as(u8, 23), (try UserSettings.decode(std.testing.allocator, unchanged)).font_size);
}

test "settings codec allocation failures release encoded owners" {
    try std.testing.checkAllAllocationFailures(std.testing.allocator, checkSettingsCodecAllocations, .{});
}
fn checkSettingsCodecAllocations(allocator: std.mem.Allocator) !void {
    const settings: UserSettings = .{ .theme_index = 3, .font_size = 20, .default_shell = .nu };
    const bytes = try settings.encodeAlloc(allocator);
    defer allocator.free(bytes);
    try std.testing.expectEqualDeep(settings, try UserSettings.decode(allocator, bytes));
}
