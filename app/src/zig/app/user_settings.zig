test "Lua modules reject traversal, bytecode and oversized sources; reload sees module changes" {
    var temp = std.testing.tmpDir(.{});
    defer temp.cleanup();
    const root = try temp.dir.realpathAlloc(std.testing.allocator, ".");
    defer std.testing.allocator.free(root);
    const path = try std.fs.path.join(std.testing.allocator, &.{ root, "init.lua" });
    defer std.testing.allocator.free(path);
    try temp.dir.writeFile(.{ .sub_path = "init.lua", .data = "require('appearance')" });
    try temp.dir.writeFile(.{ .sub_path = "appearance.lua", .data = "vex.config.font_size = 17" });
    try std.testing.expectEqual(@as(u8, 17), (try loadUserSettings(std.testing.allocator, path)).font_size);
