    defer std.testing.allocator.free(unchanged);
    try std.testing.expectEqualDeep(UserSettings{}, try UserSettings.decode(std.testing.allocator, unchanged));
    const module = try files.readFileAlloc(std.testing.allocator, "font.lua", max_config_bytes);
    defer std.testing.allocator.free(module);
    try std.testing.expectEqualStrings("return {size = 18}", module);
    try files.writeFile(.{ .sub_path = "init.lua", .data = "vex.config.font_size = " });
    var diagnostic: SettingsDiagnostic = .{};
    try std.testing.expectError(error.InvalidLuaSettings, loadUserSettingsDiagnostic(std.testing.allocator, path, &diagnostic));
    try std.testing.expect(std.mem.indexOf(u8, diagnostic.message(), "init.lua") != null);
    try saveUserSettings(std.testing.allocator, path, next);
    const malformed = try files.readFileAlloc(std.testing.allocator, "init.lua", max_config_bytes);
    defer std.testing.allocator.free(malformed);
    try std.testing.expectEqualDeep(next, try UserSettings.decode(std.testing.allocator, malformed));
}

