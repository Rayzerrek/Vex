/// A persisted shell preset; custom CLI launches remain startup-owned.
pub const DefaultShell = enum(u32) {
    startup = 0,
    cmd = 1,
    powershell = 2,
    pwsh = 3,
    nu = 4,
    gitbash = 5,
    wsl = 7,
    _,

    pub fn parse(text: []const u8) !DefaultShell {
        if (std.meta.stringToEnum(DefaultShell, text)) |value| return value;
        if (!std.mem.startsWith(u8, text, "custom:")) return error.InvalidDefaultShell;
        const id = std.fmt.parseInt(u32, text[7..], 10) catch return error.InvalidDefaultShell;
        if (id < 256 or id == std.math.maxInt(u32)) return error.InvalidDefaultShell;
        return @enumFromInt(id);
    }
};

/// Lua diagnostics retain source filenames and line numbers without retaining the VM.
pub const SettingsDiagnostic = struct {
    bytes: [512]u8 = [_]u8{0} ** 512,

    pub fn message(self: *const SettingsDiagnostic) []const u8 {
        return std.mem.sliceTo(&self.bytes, 0);
    }
};

/// Validated preferences; Lua is destroyed before these values reach the terminal.
pub const UserSettings = struct {
    theme_index: u8 = themes.default_dark_index,
    font_size: u8 = 14,
    font_family: [128]u8 = default_font,
    cursor_blink: bool = true,
    copy_on_select: bool = true,
    active_pane_border: bool = true,
    confirm_close: bool = true,
    default_shell: DefaultShell = .startup,
    ui_density: UiDensity = .comfortable,

    pub fn fontFamily(self: *const UserSettings) []const u8 {
        return std.mem.sliceTo(&self.font_family, 0);
    }

    pub fn validate(self: UserSettings) !void {
        const id = @intFromEnum(self.default_shell);
        if (id == 6 or (id > 7 and id < 256) or id == std.math.maxInt(u32)) return error.InvalidDefaultShell;
        const family = self.fontFamily();
        if (family.len == 0 or family.len >= self.font_family.len or !std.unicode.utf8ValidateSlice(family)) return error.InvalidUserSettings;
        for (family) |byte| if (byte < 32 or byte == 127) return error.InvalidUserSettings;
        if (self.theme_index >= themes.themes.len or self.font_size < 9 or self.font_size > 32) return error.InvalidUserSettings;
    }

    /// Executes a bounded Lua configuration against default preferences.
    pub fn decode(allocator: std.mem.Allocator, bytes: []const u8) !UserSettings {
        var diagnostic: SettingsDiagnostic = .{};
        return decodeLuaSettings(allocator, bytes, "init.lua", .{}, &diagnostic);
    }

    /// Serializes preferences as Lua.
    pub fn encodeAlloc(self: UserSettings, allocator: std.mem.Allocator) ![]u8 {
        try self.validate();
        const theme = try quoteLuaString(allocator, themes.themes[self.theme_index].name);
        defer allocator.free(theme);
        const family = try quoteLuaString(allocator, self.fontFamily());
        defer allocator.free(family);
        const shell_name = if (@intFromEnum(self.default_shell) >= 256)
            try std.fmt.allocPrint(allocator, "custom:{d}", .{@intFromEnum(self.default_shell)})
        else
            try allocator.dupe(u8, @tagName(self.default_shell));
        defer allocator.free(shell_name);
        return std.fmt.allocPrint(allocator,
            \\-- Generated by Vex Settings.
            \\vex.config.theme = {s}
            \\vex.config.appearance = "{s}"
            \\vex.config.ui_density = "{s}"
            \\vex.config.font_family = {s}
            \\vex.config.font_size = {d}
            \\vex.config.cursor_blink = {s}
            \\vex.config.copy_on_select = {s}
            \\vex.config.confirm_close = {s}
            \\vex.config.active_pane_border = {s}
            \\vex.config.default_shell = "{s}"
            \\
        , .{ theme, if (themes.themes[self.theme_index].is_dark) "dark" else "light", @tagName(self.ui_density), family, self.font_size, if (self.cursor_blink) "true" else "false", if (self.copy_on_select) "true" else "false", if (self.confirm_close) "true" else "false", if (self.active_pane_border) "true" else "false", shell_name });
    }
};

pub const default_font: [128]u8 = "Cascadia Mono".* ++ [_]u8{0} ** (128 - "Cascadia Mono".len);
const max_config_bytes = 64 * 1024;

pub fn quoteLuaString(allocator: std.mem.Allocator, text: []const u8) ![]u8 {
    var length: usize = 2;
    for (text) |byte| length += if (byte == '"' or byte == '\\') @as(usize, 2) else 1;
    const output = try allocator.alloc(u8, length);
    output[0] = '"';
    var index: usize = 1;
    for (text) |byte| {
        if (byte == '"' or byte == '\\') {
            output[index] = '\\';
            index += 1;
        }
        output[index] = byte;
        index += 1;
    }
    output[index] = '"';
    return output;
}

fn decodeLuaSettings(allocator: std.mem.Allocator, bytes: []const u8, path: []const u8, defaults: UserSettings, diagnostic: *SettingsDiagnostic) !UserSettings {
    if (bytes.len > max_config_bytes) return error.SettingsFileTooLarge;
    const source_path = try allocator.dupeZ(u8, path);
    defer allocator.free(source_path);
    var raw: lua.VexLuaSettings = std.mem.zeroes(lua.VexLuaSettings);
    const theme = themes.themes[defaults.theme_index].name;
    @memcpy(raw.theme[0..theme.len], theme);
    @memcpy(raw.font_family[0..defaults.fontFamily().len], defaults.fontFamily());
    const shell_name = if (@intFromEnum(defaults.default_shell) >= 256)
        try std.fmt.allocPrint(allocator, "custom:{d}", .{@intFromEnum(defaults.default_shell)})
    else
        try allocator.dupe(u8, @tagName(defaults.default_shell));
    defer allocator.free(shell_name);
    @memcpy(raw.default_shell[0..shell_name.len], shell_name);
    const density_name = @tagName(defaults.ui_density);
    @memcpy(raw.ui_density[0..density_name.len], density_name);
    raw.font_size = defaults.font_size;
    raw.cursor_blink = defaults.cursor_blink;
    raw.copy_on_select = defaults.copy_on_select;
    raw.confirm_close = defaults.confirm_close;
    raw.active_pane_border = defaults.active_pane_border;
    diagnostic.* = .{};
    const source = if (std.mem.startsWith(u8, bytes, "\xef\xbb\xbf")) bytes[3..] else bytes;
    switch (lua.vex_lua_settings_decode(source.ptr, source.len, source_path.ptr, &raw, &diagnostic.bytes, diagnostic.bytes.len)) {
        0 => {},
        2 => return error.LuaMemoryLimit,
        else => return error.InvalidLuaSettings,
    }
    var index: ?u8 = null;
    for (themes.themes, 0..) |candidate, i| {
        if (std.mem.eql(u8, candidate.name, std.mem.sliceTo(&raw.theme, 0))) index = @intCast(i);
    }
    var theme_index = index orelse return error.UnknownSettingsTheme;
    const appearance = std.mem.sliceTo(&raw.appearance, 0);
    if (!std.mem.eql(u8, appearance, "theme")) {
        const dark = if (std.mem.eql(u8, appearance, "dark")) true else if (std.mem.eql(u8, appearance, "light")) false else return error.InvalidSettingsAppearance;
        if (themes.themes[theme_index].is_dark != dark) theme_index = @intCast(if (dark) themes.default_dark_index else themes.default_light_index);
    }
    const result: UserSettings = .{
        .theme_index = theme_index,
        .font_size = @intCast(raw.font_size),
        .font_family = raw.font_family,
        .cursor_blink = raw.cursor_blink,
        .copy_on_select = raw.copy_on_select,
        .confirm_close = raw.confirm_close,
        .active_pane_border = raw.active_pane_border,
        .default_shell = try DefaultShell.parse(std.mem.sliceTo(&raw.default_shell, 0)),
        .ui_density = std.meta.stringToEnum(UiDensity, std.mem.sliceTo(&raw.ui_density, 0)) orelse return error.InvalidUiDensity,
    };
    try result.validate();
    return result;
}

pub fn companionPathAlloc(allocator: std.mem.Allocator, path: []const u8, suffix: []const u8) ![]u8 {
    if (std.fs.path.dirname(path) == null) return error.InvalidSettingsPath;
    const stem = path[0 .. path.len - std.fs.path.extension(path).len];
    return std.fmt.allocPrint(allocator, "{s}.{s}.lua", .{ stem, suffix });
}

fn loadLuaFile(allocator: std.mem.Allocator, path: []const u8, defaults: UserSettings, diagnostic: *SettingsDiagnostic) !UserSettings {
    const bytes = std.fs.cwd().readFileAlloc(allocator, path, max_config_bytes) catch |err| switch (err) {
        error.FileNotFound => return defaults,
        else => return err,
    };
    defer allocator.free(bytes);
    return decodeLuaSettings(allocator, bytes, path, defaults, diagnostic);
}

/// Loads init.lua; absent files require no setup and produce no warning.
pub fn loadUserSettings(allocator: std.mem.Allocator, path: []const u8) !UserSettings {
    var diagnostic: SettingsDiagnostic = .{};
    return loadUserSettingsDiagnostic(allocator, path, &diagnostic);
}

/// Returns source diagnostics for malformed Lua without modifying the configuration.
pub fn loadUserSettingsDiagnostic(allocator: std.mem.Allocator, path: []const u8, diagnostic: *SettingsDiagnostic) !UserSettings {
    diagnostic.* = .{};
    return loadLuaFile(allocator, path, .{}, diagnostic);
}

/// Atomically replaces preferences, preserving the previous Lua source for recovery.
/// The backup must succeed first: GUI saves must never silently destroy hand-written Lua.
pub fn saveUserSettings(allocator: std.mem.Allocator, path: []const u8, settings: UserSettings) !void {
    const parent = std.fs.path.dirname(path) orelse return error.InvalidSettingsPath;
    try std.fs.cwd().makePath(parent);
    var dir = try std.fs.cwd().openDir(parent, .{});
    defer dir.close();
    const bytes = try settings.encodeAlloc(allocator);
    defer allocator.free(bytes);
    const previous = dir.readFileAlloc(allocator, std.fs.path.basename(path), max_config_bytes) catch |err| switch (err) {
        error.FileNotFound => null,
        else => return err,
    };
    defer if (previous) |source| allocator.free(source);
    if (previous) |source| {
        if (std.mem.eql(u8, source, bytes)) return;
        const backup = try companionPathAlloc(allocator, path, "backup");
        defer allocator.free(backup);
        try atomicWrite(&dir, std.fs.path.basename(backup), source);
    }
    try atomicWrite(&dir, std.fs.path.basename(path), bytes);
}

fn atomicWrite(dir: *std.fs.Dir, name: []const u8, bytes: []const u8) !void {
    var file = try dir.atomicFile(name, .{ .write_buffer = &.{} });
    defer file.deinit();
    try file.file_writer.file.writeAll(bytes);
    try file.finish();
}

/// Resolves configuration once at startup; selftests always require an isolated absolute path.
pub fn userSettingsPathAlloc(allocator: std.mem.Allocator) ![]u8 {
    const selftest = std.process.getEnvVarOwned(allocator, "VEX_NATIVE_SELFTEST") catch |err| switch (err) {
        error.EnvironmentVariableNotFound => null,
        else => return err,
    };
    defer if (selftest) |value| allocator.free(value);
    if (selftest) |value| if (std.mem.eql(u8, value, "1")) return absoluteEnvPath(allocator, "VEX_NATIVE_SETTINGS_PATH");
    if (absoluteEnvPath(allocator, "VEX_CONFIG")) |path| return path else |err| switch (err) {
        error.EnvironmentVariableNotFound => {},
        else => return err,
    }
    const local = try absoluteEnvPath(allocator, "LOCALAPPDATA");
    defer allocator.free(local);
    return std.fs.path.join(allocator, &.{ local, "Vex", "init.lua" });
}

fn absoluteEnvPath(allocator: std.mem.Allocator, name: []const u8) ![]u8 {
    const value = try std.process.getEnvVarOwned(allocator, name);
    if (!std.fs.path.isAbsolute(value)) {
        allocator.free(value);
        return error.InvalidSettingsPath;
    }
    return value;
}

test "density defaults remain compatible and every preset round trips through Lua" {
    const allocator = std.testing.allocator;
    try std.testing.expectEqual(UiDensity.comfortable, (try UserSettings.decode(allocator, "")).ui_density);
    for (std.enums.values(UiDensity)) |value| {
        const input: UserSettings = .{ .ui_density = value };
        const encoded = try input.encodeAlloc(allocator);
        defer allocator.free(encoded);
        try std.testing.expectEqualDeep(input, try UserSettings.decode(allocator, encoded));
    }
    try std.testing.expectError(error.InvalidUiDensity, UserSettings.decode(allocator, "vex.config.ui_density = 'tiny'"));
    try std.testing.expectError(error.InvalidLuaSettings, UserSettings.decode(allocator, "vex.config.ui_density = 1"));
}

