"""Regenerate checked-in D3D12 shader bytecode using Windows' system compiler.

No compiler DLL is loaded by the app. Run from any directory with Python on Windows.
"""
import ctypes
from ctypes import wintypes
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/windows/renderer/terminal_shaders.hlsl"
OUTPUT = ROOT / "src/windows/renderer/terminal_shaders.generated.h"
CALL = ctypes.WINFUNCTYPE
HRESULT = ctypes.c_int32


def blob_method(blob, index, result, *arguments):
    vtable = ctypes.cast(blob, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    return CALL(result, ctypes.c_void_p, *arguments)(vtable[index])


def blob_bytes(blob):
    pointer = blob_method(blob, 3, ctypes.c_void_p)(blob)
    length = blob_method(blob, 4, ctypes.c_size_t)(blob)
    return ctypes.string_at(pointer, length)


def compile_shader(entry, profile):
    compiler = ctypes.WinDLL("d3dcompiler_47.dll")
    compile_fn = compiler.D3DCompile
    compile_fn.restype = HRESULT
    compile_fn.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p,
                           ctypes.c_void_p, ctypes.c_void_p, ctypes.c_char_p, ctypes.c_char_p,
                           wintypes.UINT, wintypes.UINT, ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    source = SOURCE.read_bytes()
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    try:
        result = compile_fn(source, len(source), SOURCE.name.encode(), None, None,
                            entry.encode(), profile.encode(), (1 << 11) | (1 << 15), 0,
                            ctypes.byref(code), ctypes.byref(errors))
        if result < 0:
            raise RuntimeError(blob_bytes(errors).decode() if errors else f"Shader compile failed: {result}")
        return blob_bytes(code)
    finally:
        for blob in (code, errors):
            if blob:
                blob_method(blob, 2, wintypes.ULONG)(blob)


lines = ["// Generated by tools/compile_terminal_shaders.py; edit terminal_shaders.hlsl instead.", "#pragma once"]
for entry, profile in (("terminalVertex", "vs_5_0"), ("terminalPixel", "ps_5_0")):
    data = compile_shader(entry, profile)
    lines.append(f"static const unsigned char {entry}Shader[] = {{")
    lines.extend("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + ","
                 for offset in range(0, len(data), 16))
    lines.append("};")
OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
